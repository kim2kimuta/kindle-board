# 日付ごとの例外：この日はひらがなのままにする語
KEEP = {
    "06-13": {"きた"},          # かえって きたよ（補助の「きた」）
    "11-26": {"かいて"},        # ペンで ものを かいて（絵もふくむ）
    "11-30": {"かいた"},        # まんがを かいた
}
EXTRA = {"04-28": {"きた": "来た"}, "11-02": {"かいて": "書いて"}}

SEP = re.compile(r"([ 、。「」（）！？…・])")


def convert(text, day):
    words = dict(WORDS, **EXTRA.get(day, {}))
    for w in KEEP.get(day, ()):
        words.pop(w, None)
    return "".join(words.get(p, p) for p in SEP.split(text))


def main():
    path = HERE / "data" / "kinenbi.json"
    # 「1日1行」と月ごとの空行をそのまま残すため、行ごとに書きかえる
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r'^("\d\d-\d\d"): (\{.*\})(,?)$', line)
        if m:
            day, v = json.loads(m[1]), json.loads(m[2])
            v["title"] = convert(v["title"], day)
            v["text"] = convert(v["text"], day)
            line = f"{m[1]}: {json.dumps(v, ensure_ascii=False)}{m[3]}"
        out.append(line)
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
